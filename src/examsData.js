function inferExamCategory(exam) {
  const text = normalizeExamText(exam.name);

  for (const rule of categoryRules) {
    if (rule.terms.some((term) => text.includes(normalizeExamText(term)))) {
      return rule.category;
    }
  }

  return "Bioquímica";
}

function normalizeExamText(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

